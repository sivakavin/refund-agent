CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA extensions;

INSERT INTO storage.buckets (id, name, public)
VALUES ('refund-policies', 'refund-policies', FALSE)
ON CONFLICT (id) DO UPDATE SET public = FALSE;

CREATE TABLE IF NOT EXISTS public.refund_policy_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_path TEXT NOT NULL,
    document_name TEXT NOT NULL,
    source_version TEXT NOT NULL DEFAULT '',
    chunk_index INTEGER NOT NULL,
    content TEXT NOT NULL,
    embedding extensions.vector(384) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (storage_path, chunk_index)
);

ALTER TABLE public.refund_policy_chunks ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.refund_policy_chunks TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.refund_policy_chunks_id_seq TO service_role;

CREATE INDEX IF NOT EXISTS refund_policy_chunks_embedding_idx
ON public.refund_policy_chunks
USING hnsw (embedding extensions.vector_cosine_ops);

CREATE OR REPLACE FUNCTION public.match_refund_policy(
    query_embedding extensions.vector(384),
    match_count INTEGER DEFAULT 4
)
RETURNS TABLE (
    document_name TEXT,
    storage_path TEXT,
    content TEXT,
    similarity DOUBLE PRECISION
)
LANGUAGE SQL
STABLE
SET search_path = public, extensions
AS $$
    SELECT
        policy.document_name,
        policy.storage_path,
        policy.content,
        (1 - (policy.embedding OPERATOR(extensions.<=>) query_embedding))::DOUBLE PRECISION
    FROM public.refund_policy_chunks AS policy
    ORDER BY policy.embedding OPERATOR(extensions.<=>) query_embedding
    LIMIT GREATEST(match_count, 0);
$$;

REVOKE ALL ON FUNCTION public.match_refund_policy(extensions.vector, INTEGER)
FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.match_refund_policy(extensions.vector, INTEGER)
TO service_role;
